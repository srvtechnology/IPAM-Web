import { z } from "zod";

export const createBannerSchema = z.object({
  code: z.string().min(1).optional(),
  name: z.string().min(1, "Sponsor or campaign name is required"),
  slot: z.string().min(1, "Page placement is required"),
  contract: z.string().optional().default("IPAM-COMMERCIAL-2026"),
  monthlyFee: z.coerce.number().nonnegative().optional().default(150),
  subscriptionCadence: z.enum(["MONTHLY", "HALF_YEARLY", "YEARLY"]).optional().default("MONTHLY"),
  scheduleStatus: z.enum(["ACTIVE", "SCHEDULED", "EXPIRED", "PAUSED"]).optional(),
  startDate: z.coerce.date().optional(),
  endDate: z.coerce.date().optional(),
  bannerImageUrl: z.string().optional().default("/images/sponsor_banking_banner.jpg"),
  targetUrl: z.string().optional().default("#"),
  industry: z.string().optional(),
  dimensions: z.string().optional(),
  active: z.boolean().optional().default(true),
  headline: z.string().optional(),
  description: z.string().optional(),
  badge: z.string().optional(),
  ctaText: z.string().optional(),
  pages: z.array(z.string()).optional(),
  order: z.coerce.number().optional(),
  contactName: z.string().optional(),
  contactEmail: z.string().email().optional().or(z.literal("")),
  contactPhone: z.string().optional(),
  contactTitle: z.string().optional(),
  contactAddress: z.string().optional(),
  contactTaxId: z.string().optional(),
  invoiceNumber: z.string().optional(),
  invoiceDate: z.coerce.date().optional(),
  invoiceDueDate: z.coerce.date().optional(),
  invoiceStatus: z.enum(["PAID", "PENDING", "OVERDUE"]).optional(),
  autoRenew: z.boolean().default(false),
  notes: z.string().optional(),
});

export const updateBannerSchema = createBannerSchema.partial();
